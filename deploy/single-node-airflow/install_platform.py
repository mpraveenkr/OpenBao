    run_cmd(["chmod", "-R", "775", str(FAST_DATA_ROOT)], sudo=True)
    run_cmd(["chmod", "-R", "775", str(DATA_LAKE_ROOT)], sudo=True)
    log_success("Created and permissioned platform directories.")


