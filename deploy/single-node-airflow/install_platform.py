def log_info(message: str) -> None:
    print(f"{BLUE}{BOLD}[*]{RESET} {message}")


def log_success(message: str) -> None:
    print(f"{GREEN}{BOLD}[+]{RESET} {message}")


def log_warning(message: str) -> None:
    print(f"{YELLOW}{BOLD}[!]{RESET} {message}")


def log_error(message: str) -> None:
    print(f"{RED}{BOLD}[-]{RESET} {message}")


def run_cmd(
    command: list[str],
    *,
    sudo: bool = False,
    check: bool = True,
    cwd: Path | None = None,
) -> subprocess.CompletedProcess[str]:
    if sudo and os.getuid() != 0:
        command = ["sudo", *command]
    result = subprocess.run(
        command,
        check=False,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        cwd=cwd,
    )
    if check and result.returncode != 0:
        log_error(f"Command failed: {' '.join(command)}")
        if result.stdout:
            print(result.stdout)
        if result.stderr:
            print(result.stderr)
        raise SystemExit(result.returncode)
    return result


def secure_token(length: int) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def fernet_key() -> str:
    import base64

    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii")


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw_line in path.read_text().splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def write_env(path: Path, values: dict[str, str]) -> None:
    ordered_keys = [*DEFAULTS.keys(), *SECRET_KEYS.keys(), "AIRFLOW_UID"]
    emitted = set()
    lines = [
        "# Generated by deploy/single-node-airflow/install_platform.py.",
        "# Existing values are preserved on re-run unless --rotate-secrets is used.",
    ]
    for key in ordered_keys:
        if key in values:
            lines.append(f"{key}={values[key]}")
            emitted.add(key)
    for key in sorted(set(values) - emitted):
        lines.append(f"{key}={values[key]}")
    path.write_text("\n".join(lines) + "\n")
    path.chmod(stat.S_IRUSR | stat.S_IWUSR)


def build_env(rotate_secrets: bool) -> dict[str, str]:
    env_path = DEPLOY_DIR / ".env"
    values = read_env(env_path)
    for key, value in DEFAULTS.items():
        values.setdefault(key, value)
    values.setdefault("AIRFLOW_UID", "50000")
    for key, length in SECRET_KEYS.items():
        if rotate_secrets or key not in values:
            values[key] = secure_token(length)
    if rotate_secrets or "AIRFLOW_FERNET_KEY" not in values:
        values["AIRFLOW_FERNET_KEY"] = fernet_key()
    return values


def verify_user(yes: bool) -> None:
    current_user = os.environ.get("USER", "")
    if current_user == EXPECTED_USER:
        return
    log_warning(f"This script is optimized to run as '{EXPECTED_USER}'. Current user is '{current_user}'.")
    if not yes:
        choice = input("Proceed anyway? (y/N): ").strip().lower()
        if choice != "y":
            raise SystemExit(1)


def validate_mounts(skip_mount_check: bool) -> None:
    if skip_mount_check:
        log_warning("Skipping mount validation by request.")
        return
    for mount in (FAST_DATA_ROOT, DATA_LAKE_ROOT):
        if not mount.exists():
            log_error(f"Required mount path does not exist: {mount}")
            raise SystemExit(1)
        result = run_cmd(["findmnt", "--target", str(mount)], check=False)
        if result.returncode != 0:
            log_error(f"Required path is not a mounted filesystem: {mount}")
            raise SystemExit(1)
    log_success("Validated fast_data and data_lake mounts.")


def install_ca_certificate(yes: bool) -> None:
    source = DEPLOY_DIR / CERT_FILE_NAME
    if not source.exists():
        source = Path.cwd() / CERT_FILE_NAME
    if not source.exists():
        log_warning(f"Could not find {CERT_FILE_NAME}.")
        if not yes:
            choice = input("Proceed without importing the Cisco Umbrella CA? (y/N): ").strip().lower()
            if choice != "y":
                raise SystemExit(0)
        return

    log_info("Installing Cisco Umbrella CA into host trust store.")
    target = Path("/usr/local/share/ca-certificates") / CERT_FILE_NAME
    run_cmd(["cp", str(source), str(target)], sudo=True)
    run_cmd(["update-ca-certificates"], sudo=True)
    shutil.copy2(source, DEPLOY_DIR / "config" / CERT_FILE_NAME)
    log_success("CA installed on host and copied into deployment config.")


def install_docker() -> None:
    if shutil.which("docker"):
        log_success("Docker is already installed.")
        return
    log_info("Installing Docker Engine and Compose plugin.")
    run_cmd(["apt-get", "update"], sudo=True)
    run_cmd(
        ["apt-get", "install", "-y", "apt-transport-https", "ca-certificates", "curl", "gnupg", "lsb-release"],
        sudo=True,
    )
    run_cmd(["install", "-m", "0755", "-d", "/etc/apt/keyrings"], sudo=True)
    run_cmd(
        [
            "bash",
            "-c",
            "curl -fsSL https://download.docker.com/linux/ubuntu/gpg "
            "| gpg --dearmor --yes -o /etc/apt/keyrings/docker.gpg",
        ],
        sudo=True,
    )
    arch = run_cmd(["dpkg", "--print-architecture"]).stdout.strip()
    codename = run_cmd(["lsb_release", "-cs"]).stdout.strip()
    repo = (
        f"deb [arch={arch} signed-by=/etc/apt/keyrings/docker.gpg] "
        f"https://download.docker.com/linux/ubuntu {codename} stable"
    )
    run_cmd(["bash", "-c", f"echo '{repo}' > /etc/apt/sources.list.d/docker.list"], sudo=True)
    run_cmd(["apt-get", "update"], sudo=True)
    run_cmd(["apt-get", "install", "-y", "docker-ce", "docker-ce-cli", "containerd.io", "docker-compose-plugin"], sudo=True)
    run_cmd(["systemctl", "enable", "--now", "docker"], sudo=True)
    run_cmd(["usermod", "-aG", "docker", EXPECTED_USER], sudo=True)
    log_success("Docker Engine and Compose plugin installed.")


