def sync_ingestion_dags(values: dict[str, str]) -> None:
    sources = [
        DEPLOY_DIR / "dags" / "ingestion_smoke_test.py",
        *sorted((DEPLOY_DIR / "dags" / "generated").glob("*.py")),
    ]
    for source in sources:
        target = Path(values["AIRFLOW_DAGS_PATH"]) / source.name
        run_cmd(["cp", str(source), str(target)], sudo=True)
        run_cmd(["chown", f"{EXPECTED_USER}:0", str(target)], sudo=True)
        run_cmd(["chmod", "664", str(target)], sudo=True)
    log_success(f"Installed {len(sources)} DAGs at {values['AIRFLOW_DAGS_PATH']}.")


def compose_config() -> None:
    log_info("Validating Docker Compose configuration.")
    run_cmd(["docker", "compose", "--env-file", ".env", "config"], check=True, cwd=DEPLOY_DIR)
    log_success("Docker Compose configuration is valid.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Bootstrap the single-node Airflow ingestion platform.")
    parser.add_argument("--yes", action="store_true", help="Accept prompts for non-destructive choices.")
    parser.add_argument("--skip-docker-install", action="store_true", help="Do not install Docker if missing.")
    parser.add_argument("--skip-mount-check", action="store_true", help="Do not require /mnt paths to be mounted.")
    parser.add_argument("--rotate-secrets", action="store_true", help="Regenerate all generated secrets.")
    parser.add_argument(
        "--sync-dags-only",
        action="store_true",
        help="Copy generated DAGs to the configured Airflow DAG folder and exit.",
    )
    args = parser.parse_args()

    print(f"{BOLD}Single-Node Airflow Ingestion Platform Bootstrap{RESET}")
    if args.sync_dags_only:
        values = read_env(DEPLOY_DIR / ".env")
        if "AIRFLOW_DAGS_PATH" not in values:
            log_error("deploy/single-node-airflow/.env is missing AIRFLOW_DAGS_PATH. Run full bootstrap first.")
            return 2
        sync_ingestion_dags(values)
        log_success("DAG sync complete.")
        return 0

    verify_user(args.yes)
    validate_mounts(args.skip_mount_check)
    install_ca_certificate(args.yes)
    if args.skip_docker_install:
        log_warning("Skipping Docker installation by request.")
    else:
        install_docker()
    values = build_env(args.rotate_secrets)
    write_env(DEPLOY_DIR / ".env", values)
    create_directories(values)
    write_generated_scripts()
    sync_ingestion_dags(values)
    compose_config()

    log_success("Bootstrap files and directories are ready.")
    print(f"Next: cd {DEPLOY_DIR} && docker compose --env-file .env up -d --build")
    print(f"Airflow admin: {values['AIRFLOW_ADMIN_USERNAME']} / see deploy/single-node-airflow/.env")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
